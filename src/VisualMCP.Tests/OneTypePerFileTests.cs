using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Diagnostics;
using Snitch.Languages.CSharp.Inspections;
using Xunit;

namespace VisualMCP.Tests;

/// <summary>
/// VMC0001, the "one type per file" house rule that the in-process "house" pack puts in front of
/// inspect_code. The analyzer is syntactic on purpose: it must answer for a file even when the
/// project around it does not compile.
/// </summary>
public sealed class OneTypePerFileTests
{
    [Fact]
    public void AFileWithASingleTypeIsClean() => Assert.Empty(Diagnostics("""
        namespace Probe;

        internal class OnlyType
        {
        }
        """));

    [Fact]
    public void NestedTypesBelongToTheirContainer() => Assert.Empty(Diagnostics("""
        namespace Probe;

        internal class Outer
        {
            internal class Inner { }
            private enum Mode { A, B }
        }
        """));

    [Fact]
    public void PartialDeclarationsOfTheSameTypeCountOnce() => Assert.Empty(Diagnostics("""
        namespace Probe;

        internal partial class Split { }
        internal partial class Split { }
        """));

    [Fact]
    public void TwoTypesInOneFileAreReported() => Assert.Single(Diagnostics("""
        namespace Probe;

        internal class First { }
        internal class Second { }
        """));

    [Fact]
    public void TypesInDifferentNamespaceBlocksAreStillCounted() => Assert.Single(Diagnostics("""
        namespace Probe.One
        {
            internal interface IContract { }
        }

        namespace Probe.Two
        {
            internal class Implementation { }
        }
        """));

    [Fact]
    public void TheMessageNamesEveryTypeInTheFile()
    {
        var diagnostic = Assert.Single(Diagnostics("""
            namespace Probe;

            internal class First { }
            internal class Second { }
            """));
        Assert.Contains("Probe.First", diagnostic.GetMessage());
        Assert.Contains("Probe.Second", diagnostic.GetMessage());
    }

    [Fact]
    public void AnEnumAndADelegateCountAsTypes() => Assert.Single(Diagnostics("""
        namespace Probe;

        internal enum Mode { A }
        internal delegate void Handler(int value);
        """));

    [Fact]
    public void GeneratedFilesAreSkipped()
    {
        var tree = CSharpSyntaxTree.ParseText("""
            // <auto-generated/>
            namespace Probe;

            internal class First { }
            internal class Second { }
            """, path: "Probe.g.cs");

        Assert.Empty(Diagnostics(tree));
    }

    [Fact]
    public void TheRuleIsAnEnabledSuggestion()
    {
        var descriptor = new OneTypePerFileAnalyzer().SupportedDiagnostics.Single();

        Assert.Equal(OneTypePerFileAnalyzer.RuleId, descriptor.Id);
        Assert.True(descriptor.IsEnabledByDefault);
        Assert.Equal(DiagnosticSeverity.Info, descriptor.DefaultSeverity);
        Assert.Equal("Style", descriptor.Category);
    }

    [Fact]
    public async Task TheHousePackReportsTheRuleThroughInspectCode()
    {
        using var workspace = FakeWorkspace.Create(
            ("One.cs", "namespace Probe; internal class One { }"),
            ("Two.cs", "namespace Probe; internal class Two { } internal class Three { }"));
        var service = new InspectCodeService(workspace);

        var report = await service.RunAsync(
            projectName: null, filePath: null, packs: "house", minSeverity: "info",
            ids: null, excludeIds: null, enableAll: true, maxResults: 100, timeoutSeconds: 60);

        Assert.Equal("completed", report.State);
        Assert.Contains("house", report.Packs);
        Assert.Contains(report.Findings, finding =>
            finding.InspectionId == OneTypePerFileAnalyzer.RuleId && finding.File.EndsWith("Two.cs"));
        Assert.DoesNotContain(report.Findings, finding =>
            finding.InspectionId == OneTypePerFileAnalyzer.RuleId && finding.File.EndsWith("One.cs"));
    }

    private static ImmutableArray<Diagnostic> Diagnostics(string source) =>
        Diagnostics(CSharpSyntaxTree.ParseText(source, path: "Probe.cs"));

    private static ImmutableArray<Diagnostic> Diagnostics(SyntaxTree tree)
    {
        var compilation = CSharpCompilation.Create(
            "Probe",
            new[] { tree },
            new[] { MetadataReference.CreateFromFile(typeof(object).Assembly.Location) },
            new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary));

        return compilation
            .WithAnalyzers(ImmutableArray.Create<DiagnosticAnalyzer>(new OneTypePerFileAnalyzer()))
            .GetAnalyzerDiagnosticsAsync()
            .GetAwaiter()
            .GetResult();
    }
}
