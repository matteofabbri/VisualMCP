using System.Text;
using Microsoft.CodeAnalysis.CSharp;

namespace Snitch.Metacode.Generation;

/// <summary>How the C# is written: indentation, namespace form, the using directives a file starts with.</summary>
public sealed record CSharpEmitOptions
{
    public static CSharpEmitOptions Default { get; } = new();

    public string Indent { get; init; } = "    ";

    public string NewLine { get; init; } = "\n";

    /// <summary>A single namespace becomes <c>namespace X;</c> instead of a braced block.</summary>
    public bool FileScopedNamespaces { get; init; } = true;

    /// <summary>Usings written above the first declaration. The ones the code needs are added to these.</summary>
    public IReadOnlyList<string>? Usings { get; init; }

    /// <summary>Write the using directives at all — false for a snippet meant to be pasted into a file.</summary>
    public bool IncludeUsings { get; init; } = true;

    /// <summary>Prefix the file with a line saying what produced it.</summary>
    public bool IncludeHeader { get; init; }
}

/// <summary>
/// What one emission produced: the C# source, every namespace the result references (so a caller
/// writing a file knows what to import), and every place the model said something C# cannot express —
/// which is written as a comment in the code and repeated here instead of being dropped.
/// </summary>
public sealed record CSharpEmitResult(
    string Code,
    IReadOnlyList<string> Usings,
    IReadOnlyList<string> Diagnostics);

/// <summary>
/// Prints a <see cref="MetacodeDocument"/> as C# — the inverse of <see cref="Frontends.CSharpFrontend"/>,
/// and the first target of "generate new code from metacode". It is a separate writer and not a Roslyn
/// syntax factory on purpose: the model is the source of truth, and every construct it cannot express
/// (a Python import, a comprehension, a <c>**</c> operator) is lowered to the closest C# that compiles,
/// with a comment and a diagnostic saying what was approximated.
/// </summary>
/// <remarks>
/// The emitter is the counterpart of <see cref="Rendering.PseudocodeRenderer"/>: same traversal, same
/// precedence table, different target syntax. It never invents members: a declaration without a body in
/// an interface prints <c>;</c>, one in a class prints an empty body. A module of free functions — the
/// shape a pseudocode file has — is wrapped in a static class, because C# has no file-scope function.
/// </remarks>
public sealed class CSharpEmitter
{
    private readonly CSharpEmitOptions _options;

    public CSharpEmitter(CSharpEmitOptions? options = null) => _options = options ?? CSharpEmitOptions.Default;

    /// <summary>A whole file: modules, their declarations, and the namespace(s) they belong to.</summary>
    public CSharpEmitResult Emit(MetacodeDocument document) => new Writer(_options).WriteDocument(document);

    /// <summary>One declaration, as a snippet — no namespace, and usings only when asked for.</summary>
    public CSharpEmitResult Emit(MetacodeDeclaration declaration) => new Writer(_options).WriteDeclaration(declaration);

    /// <summary>One callable, as a snippet.</summary>
    public CSharpEmitResult Emit(MetacodeFunction function) => Emit((MetacodeDeclaration)function);

    /// <summary>One block of statements, at file scope (usable as an example or a method body).</summary>
    public CSharpEmitResult Emit(MetacodeBlock block) => new Writer(_options).WriteBlockSnippet(block);

    // ── the writer: one emission, its own buffer and state ─────────────────────────────

    private sealed class Writer
    {
        private const string StatementModuleName = "<statements>";

        private readonly CSharpEmitOptions _options;
        private readonly StringBuilder _text = new();
        private readonly List<string> _diagnostics = new();
        private readonly HashSet<string> _usings = new(StringComparer.Ordinal);
        private int _depth;

        public Writer(CSharpEmitOptions options) => _options = options;

        public CSharpEmitResult WriteDocument(MetacodeDocument document)
        {
            var namespaces = document.Modules.Where(module => module.Kind == MetacodeModuleKind.Namespace).ToList();
            var modules = document.Modules.Where(module => module.Kind != MetacodeModuleKind.Namespace).ToList();

            if (_options.IncludeHeader)
                Line("// <auto-generated> written by Snitch.Metacode from " + document.Name);

            // Top-level statements must precede every type declaration, so the synthetic module the C#
            // frontend creates for them is written first, at depth 0.
            var statements = modules.FirstOrDefault(module => module.Name == StatementModuleName);
            if (statements is not null)
            {
                foreach (var function in statements.Declarations.OfType<MetacodeFunction>())
                {
                    if (function.Body is not null)
                        WriteStatements(function.Body.Statements);
                }

                if (statements.Declarations.Any(declaration => declaration is not MetacodeFunction))
                    Report("module", "a declaration next to top-level statements was written after them", statements.Origin);
            }

            var loose = modules.Where(module => module.Name != StatementModuleName).ToList();

            // A file-scoped namespace must precede every other member, so it cannot follow top-level
            // statements; a braced namespace can.
            var fileScoped = namespaces.Count == 1 && loose.Count == 0 && statements is null
                             && _options.FileScopedNamespaces && !NeedsContainer(namespaces[0]);

            if (fileScoped)
            {
                Line("namespace " + namespaces[0].Name + ";");
                Blank();
                WriteDeclarations(namespaces[0].Declarations);
            }
            else
            {
                foreach (var module in loose)
                {
                    WriteModule(module);
                    Blank();
                }

                foreach (var module in namespaces)
                {
                    Line("namespace " + module.Name);
                    Open();
                    // A namespace can hold the same shapes a file can: types, or free functions that need
                    // a container class to be C# at all.
                    WriteModule(module);
                    Close();
                    Blank();
                }
            }

            InsertUsings();
            return Result();
        }

        public CSharpEmitResult WriteDeclaration(MetacodeDeclaration declaration)
        {
            WriteDeclarationCore(declaration);
            InsertUsings();
            return Result();
        }

        public CSharpEmitResult WriteBlockSnippet(MetacodeBlock block)
        {
            WriteStatements(block.Statements);
            InsertUsings();
            return Result();
        }

        private CSharpEmitResult Result() => new(
            _text.ToString().TrimEnd('\r', '\n'),
            _usings.OrderBy(name => name, StringComparer.Ordinal).ToList(),
            _diagnostics);

        // ── using directives ────────────────────────────────────────────────────────────

        /// <summary>
        /// Written last, inserted first: only the emission itself knows which namespaces it needed.
        /// </summary>
        private void InsertUsings()
        {
            if (!_options.IncludeUsings) return;

            var usings = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var name in _options.Usings ?? Array.Empty<string>())
                usings.Add(NormalizeUsing(name));
            foreach (var name in _usings)
                usings.Add(name);

            if (usings.Count == 0) return;

            var block = new StringBuilder();
            foreach (var name in usings)
                block.Append("using ").Append(name).Append(';').Append(_options.NewLine);

            _text.Insert(0, block.Append(_options.NewLine).ToString());
        }

        private static string NormalizeUsing(string name)
        {
            var trimmed = name.Trim();
            return trimmed.StartsWith("using ", StringComparison.Ordinal)
                ? trimmed["using ".Length..].TrimEnd(';').Trim()
                : trimmed.TrimEnd(';');
        }

        private void Report(string kind, string message, MetacodeOrigin origin)
        {
            var where = origin.IsKnown ? $" at {origin.Location}" : string.Empty;
            _diagnostics.Add($"{kind}{where}: {message}");
        }

        // ── modules and declarations ────────────────────────────────────────────────────

        /// <summary>
        /// A module without a namespace: C# files without a namespace put their types at file scope, so
        /// that is the shape. Anything that cannot live at file scope (a free function, a field) is
        /// wrapped in a static class named after the module, which is what a pseudocode module means.
        /// </summary>
        private void WriteModule(MetacodeModule module)
        {
            if (!NeedsContainer(module))
            {
                WriteDeclarations(module.Declarations);
                return;
            }

            var name = SyntaxFacts.IsValidIdentifier(module.Name) ? module.Name : "Functions";
            Line("static partial class " + Identifier(name));
            Open();
            WriteDeclarations(module.Declarations);
            Close();
        }

        /// <summary>
        /// Whether a module holds something C# cannot write at file (or namespace) scope: a free
        /// function, a field, a property, an event. Those need a container class.
        /// </summary>
        private static bool NeedsContainer(MetacodeModule module) =>
            module.Declarations.Any(declaration =>
                declaration is MetacodeFunction or MetacodeProperty or MetacodeField or MetacodeEvent);

        private void WriteDeclarations(IReadOnlyList<MetacodeDeclaration> declarations)
        {
            for (var i = 0; i < declarations.Count; i++)
            {
                WriteDeclarationCore(declarations[i]);
                if (i < declarations.Count - 1) Blank();
            }
        }

        private void WriteDeclarationCore(MetacodeDeclaration declaration)
        {
            switch (declaration)
            {
                case MetacodeTypeDeclaration type:
                    WriteType(type);
                    break;
                case MetacodeFunction function:
                    WriteFunction(function, interfaceMember: false);
                    break;
                case MetacodeProperty property:
                    WriteProperty(property);
                    break;
                case MetacodeField field:
                    WriteField(field);
                    break;
                case MetacodeEvent @event:
                    Line(Modifiers(@event.Modifiers) + "event " + TypeNameOr(@event.Type, "object") + " "
                         + Identifier(@event.Name) + ";");
                    break;
                case MetacodeEnumMember member:
                    Line(Identifier(member.Name) + (member.Value is null ? string.Empty : " = " + Expression(member.Value, 0)) + ",");
                    break;
                case MetacodeTypeAlias alias:
                    Line("using " + Identifier(alias.Name)
                         + (alias.Target is null ? string.Empty : " = " + TypeName(alias.Target)) + ";");
                    break;
                case MetacodeOpaqueDeclaration opaque:
                    WriteOpaqueDeclaration(opaque);
                    break;
                default:
                    Report("declaration", $"unmodelled declaration {declaration.GetType().Name}", declaration.Origin);
                    Line("// TODO(metacode): unmodelled declaration " + declaration.GetType().Name);
                    break;
            }
        }

        private void WriteType(MetacodeTypeDeclaration type)
        {
            var keyword = type.Kind switch
            {
                MetacodeTypeKind.Struct => "struct",
                MetacodeTypeKind.Interface => "interface",
                MetacodeTypeKind.Enum => "enum",
                MetacodeTypeKind.Record => "record",
                MetacodeTypeKind.Trait => "interface",
                _ => "class",
            };

            if (type.Kind is MetacodeTypeKind.Union)
                Report("type", "a union has no C# equivalent; emitted as a class", type.Origin);
            if (type.Kind is MetacodeTypeKind.Trait)
                Report("type", "a trait has no C# equivalent; emitted as an interface", type.Origin);

            var header = new StringBuilder(Modifiers(type.Modifiers))
                .Append(keyword).Append(' ').Append(Identifier(type.Name));

            if (type.TypeParameters is { Count: > 0 })
                header.Append('<').Append(string.Join(", ", type.TypeParameters.Select(p => Identifier(p.Name)))).Append('>');

            if (type.BaseTypes is { Count: > 0 })
                header.Append(" : ").Append(string.Join(", ", type.BaseTypes.Select(TypeName)));

            Line(header.ToString());
            WriteConstraints(type.TypeParameters);
            Open();

            var members = type.Members;
            for (var i = 0; i < members.Count; i++)
            {
                switch (members[i])
                {
                    case MetacodeFunction function when type.Kind is MetacodeTypeKind.Enum:
                        Report("member", "a function inside an enum is not C#; skipped", function.Origin);
                        break;
                    case MetacodeFunction function:
                        WriteFunction(function, interfaceMember: type.Kind is MetacodeTypeKind.Interface or MetacodeTypeKind.Trait);
                        break;
                    case MetacodeEnumMember member:
                        Line(Identifier(member.Name) + (member.Value is null ? string.Empty : " = " + Expression(member.Value, 0)) + ",");
                        break;
                    case MetacodeTypeAlias alias:
                        Report("member", "a type alias is not a type member in C#; written as a comment", alias.Origin);
                        Line("// alias " + alias.Name + (alias.Target is null ? string.Empty : " = " + alias.Target.Render()));
                        break;
                    default:
                        WriteDeclarationCore(members[i]);
                        break;
                }

                if (i < members.Count - 1) Blank();
            }

            Close();
        }

        /// <summary>
        /// A type parameter's constraints are the text the source wrote (<c>class</c>, <c>new()</c>,
        /// <c>IComparable</c>); the <c>where</c> clause is rebuilt around them.
        /// </summary>
        private void WriteConstraints(IReadOnlyList<MetacodeTypeParameter>? parameters)
        {
            if (parameters is null) return;

            foreach (var parameter in parameters)
            {
                if (parameter.Constraints is not { Count: > 0 }) continue;
                Line("where " + Identifier(parameter.Name) + " : " + string.Join(", ", parameter.Constraints));
            }
        }

        private void WriteFunction(MetacodeFunction function, bool interfaceMember)
        {
            var body = function.Body;
            var parameters = "(" + string.Join(", ", function.ParameterList.Select(Parameter)) + ")";
            string header;

            switch (function.Kind)
            {
                case MetacodeFunctionKind.Constructor:
                    header = Modifiers(function.Modifiers) + Identifier(function.Name) + parameters
                             + ConstructorInitializer(ref body);
                    break;

                case MetacodeFunctionKind.Destructor:
                    // A destructor takes no modifiers in C#.
                    header = "~" + Identifier(function.Name) + "()";
                    break;

                case MetacodeFunctionKind.Operator:
                    header = Modifiers(function.Modifiers) + TypeNameOr(function.ReturnType, "void") + " "
                             + function.Name + parameters;
                    break;

                default:
                    var typeParameters = function.TypeParameters is { Count: > 0 }
                        ? "<" + string.Join(", ", function.TypeParameters.Select(p => Identifier(p.Name))) + ">"
                        : string.Empty;
                    header = Modifiers(function.Modifiers) + TypeNameOr(function.ReturnType, "void") + " "
                             + Identifier(function.Name) + typeParameters + parameters;
                    break;
            }

            var declares = body is null
                           && (interfaceMember
                               || Has(function.Modifiers, MetacodeModifiers.Abstract)
                               || Has(function.Modifiers, MetacodeModifiers.Extern)
                               || Has(function.Modifiers, MetacodeModifiers.Partial));

            if (declares)
            {
                Line(header + ";");
                WriteConstraints(function.TypeParameters);
                return;
            }

            Line(header);
            WriteConstraints(function.TypeParameters);

            if (body is null)
            {
                Open();
                Close();
                return;
            }

            Open();
            WriteStatements(body.Statements);
            Close();
        }

        /// <summary>
        /// The C# frontend folds <c>: base(args)</c> into the body as its first statement, so the inverse
        /// peels it off again. <paramref name="body"/> is the body without that statement.
        /// </summary>
        private string ConstructorInitializer(ref MetacodeBlock? body)
        {
            if (body is not { Statements.Count: > 0 }) return string.Empty;

            if (body.Statements[0] is not MetacodeExpressionStatement
                {
                    Expression: MetacodeInvocation { Callee: MetacodeIdentifier { Name: "this" or "base" } callee } invocation,
                })
                return string.Empty;

            body = body with { Statements = body.Statements.Skip(1).ToList() };
            return " : " + callee.Name + "(" + string.Join(", ", invocation.ArgumentList.Select(Argument)) + ")";
        }

        private void WriteProperty(MetacodeProperty property)
        {
            var header = new StringBuilder(Modifiers(property.Modifiers));

            var isIndexer = property.Parameters is { Count: > 0 } || property.Name == "this";
            if (isIndexer)
                header.Append(TypeNameOr(property.Type, "object")).Append(" this[")
                      .Append(string.Join(", ", (property.Parameters ?? Array.Empty<MetacodeParameter>()).Select(Parameter)))
                      .Append(']');
            else
                header.Append(TypeNameOr(property.Type, "object")).Append(' ').Append(Identifier(property.Name));

            Line(header.ToString());

            if (property.Getter is null && property.Setter is null)
            {
                Report("property", $"'{property.Name}' has no accessor; emitted as auto get/set", property.Origin);
                Open();
                Line("get;");
                Line("set;");
                Close();
            }
            else
            {
                Open();
                if (property.Getter is not null) WriteAccessor("get", property.Getter);
                if (property.Setter is not null) WriteAccessor("set", property.Setter);
                Close();
            }

            // `int P { get; set; } = 5;`: an initializer follows the accessor list.
            if (property.Initializer is not null)
                SetLineTail(" = " + Expression(property.Initializer, 0) + ";");
        }

        private void WriteAccessor(string keyword, MetacodeAccessor accessor)
        {
            // A C# set accessor's parameter is always `value`; the model may name it (Python's `self`).
            if (keyword == "set" && accessor.ParameterName is { Length: > 0 } name && name != "value")
                Report("accessor", $"a set accessor's parameter is 'value' in C#; the model called it '{name}'", accessor.Origin);

            var prefix = Modifiers(accessor.Modifiers);
            if (accessor.Body is null)
            {
                Line(prefix + keyword + ";");
                return;
            }

            // `get => value;` is what the C# frontend turns into a one-return body, so it reads back the same.
            if (accessor.Body.Statements.Count == 1 && accessor.Body.Statements[0] is MetacodeReturn { Value: { } returned })
            {
                Line(prefix + keyword + " => " + Expression(returned, 0) + ";");
                return;
            }

            Line(prefix + keyword);
            Open();
            WriteStatements(accessor.Body.Statements);
            Close();
        }

        private void WriteField(MetacodeField field)
        {
            if (field.Type is null or { IsDynamic: true })
                Report("field", $"'{field.Name}' has no type; emitted as object", field.Origin);

            var modifiers = Modifiers(field.Modifiers, isField: true, hasType: field.Type is not null);
            var type = TypeNameOr(field.Type, "object");

            Line(modifiers + type + " " + Identifier(field.Name)
                 + (field.Initializer is null ? string.Empty : " = " + Expression(field.Initializer, 0)) + ";");
        }

        private void WriteOpaqueDeclaration(MetacodeOpaqueDeclaration opaque)
        {
            Report("declaration", "kept verbatim: " + opaque.Reason, opaque.Origin);

            if (opaque.Language == MetacodeLanguage.CSharp)
            {
                // The text came from a C# tree, so it is valid C# by construction (a delegate, a conversion
                // operator, a construct the model has no node for).
                foreach (var line in RawLines(opaque.Text))
                    Line(line);
                return;
            }

            Line("// TODO(metacode): " + PseudocodeText(opaque.Text) + " // " + opaque.Reason);
        }

        // ── statements ──────────────────────────────────────────────────────────────────

        private void WriteStatements(IReadOnlyList<MetacodeStatement> statements)
        {
            foreach (var statement in statements)
                WriteStatement(statement);
        }

        private void WriteStatement(MetacodeStatement statement)
        {
            switch (statement)
            {
                case MetacodeBlock block:
                    WriteStatements(block.Statements);
                    break;

                case MetacodeLocalVariable variable:
                    Line(LocalText(variable) + ";");
                    break;

                case MetacodeAssignment assignment:
                    Line(AssignmentText(assignment) + ";");
                    break;

                case MetacodeExpressionStatement expression:
                    Line(Expression(expression.Expression, 0) + ";");
                    break;

                case MetacodeReturn @return:
                    Line(@return.Value is null ? "return;" : "return " + Expression(@return.Value, 0) + ";");
                    break;

                case MetacodeIf @if:
                    WriteIf(@if);
                    break;

                case MetacodeWhile @while:
                    Line("while (" + Expression(@while.Condition, 0) + ")");
                    WriteBody(@while.Body);
                    break;

                case MetacodeDoWhile doWhile:
                    Line("do");
                    WriteBody(doWhile.Body);
                    // The `while` belongs to the closing brace line: `} while (c);`
                    SetLineTail(" while (" + Expression(doWhile.Condition, 0) + ");");
                    break;

                case MetacodeForEach forEach:
                    WriteForEach(forEach);
                    break;

                case MetacodeFor @for:
                    WriteFor(@for);
                    break;

                case MetacodeSwitch @switch:
                    WriteSwitch(@switch);
                    break;

                case MetacodeBreak:
                    Line("break;");
                    break;

                case MetacodeContinue:
                    Line("continue;");
                    break;

                case MetacodeGoto @goto:
                    Line("goto " + @goto.Label + ";");
                    break;

                case MetacodeLabel label:
                    Line(label.Label + ":");
                    _depth++;
                    WriteStatement(label.Statement);
                    _depth--;
                    break;

                case MetacodeThrow @throw:
                    Line(@throw.Exception is null ? "throw;" : "throw " + Expression(@throw.Exception, 0) + ";");
                    break;

                case MetacodeTry @try:
                    WriteTry(@try);
                    break;

                case MetacodeUsing @using:
                    WriteUsing(@using);
                    break;

                case MetacodeLock @lock:
                    Line("lock (" + Expression(@lock.Target, 0) + ")");
                    WriteBody(@lock.Body);
                    break;

                case MetacodeYield @yield:
                    Line(@yield.Value is null ? "yield break;" : "yield return " + Expression(@yield.Value, 0) + ";");
                    break;

                case MetacodeLocalFunction local:
                    WriteFunction(local.Function, interfaceMember: false);
                    break;

                case MetacodeComment comment:
                    foreach (var line in comment.Text.Replace("\r", string.Empty).Split('\n'))
                        Line("// " + line);
                    break;

                case MetacodeImport import:
                    Report("statement", "a language import has no C# form; written as a comment", import.Origin);
                    Line("// TODO(metacode): import " + ImportText(import));
                    break;

                case MetacodeOpaqueStatement opaque:
                    WriteOpaqueStatement(opaque);
                    break;

                default:
                    Report("statement", $"unmodelled statement {statement.GetType().Name}", statement.Origin);
                    Line("// TODO(metacode): unmodelled statement " + statement.GetType().Name);
                    break;
            }
        }

        private void WriteIf(MetacodeIf @if)
        {
            Line("if (" + Expression(@if.Condition, 0) + ")");
            WriteBody(@if.Then);

            var current = @if;
            while (current.Else is not null)
            {
                // An else-if chain stays a chain: the model nests it as a single if inside the else block.
                if (current.Else.Statements.Count == 1 && current.Else.Statements[0] is MetacodeIf nested)
                {
                    Line("else if (" + Expression(nested.Condition, 0) + ")");
                    WriteBody(nested.Then);
                    current = nested;
                    continue;
                }

                Line("else");
                WriteBody(current.Else);
                return;
            }
        }

        private void WriteForEach(MetacodeForEach forEach)
        {
            var variable = forEach.VariableName.StartsWith('(')
                ? "var " + forEach.VariableName
                : TypeNameOr(forEach.VariableType, "var") + " " + Identifier(forEach.VariableName);

            Line((forEach.IsAwait ? "await " : string.Empty) + "foreach (" + variable + " in "
                 + Expression(forEach.Iterable, 0) + ")");
            WriteBody(forEach.Body);
        }

        private void WriteFor(MetacodeFor @for)
        {
            Line("for (" + InlineStatement(@for.Initializer) + "; "
                 + (@for.Condition is null ? string.Empty : Expression(@for.Condition, 0)) + "; "
                 + InlineStatement(@for.Increment) + ")");
            WriteBody(@for.Body);
        }

        private void WriteSwitch(MetacodeSwitch @switch)
        {
            Line("switch (" + Expression(@switch.Subject, 0) + ")");
            Open();

            foreach (var @case in @switch.Cases)
            {
                if (@case.IsDefault)
                {
                    Line("default:");
                }
                else
                {
                    foreach (var label in @case.Labels ?? Array.Empty<MetacodeExpression>())
                        Line("case " + CaseLabel(label) + ":");
                }

                _depth++;
                WriteStatements(@case.Body.Statements);

                // C# never falls through, so a case that does not end with a jump would not compile.
                if (!EndsWithJump(@case.Body.Statements))
                    Line("break;");

                _depth--;
            }

            Close();
        }

        /// <summary>
        /// A switch label is a pattern position: an opaque C# label was the source's pattern and is
        /// written as text, never wrapped in parentheses.
        /// </summary>
        private string CaseLabel(MetacodeExpression label) => label switch
        {
            MetacodeOpaqueExpression { Language: MetacodeLanguage.CSharp } opaque => opaque.Text,
            MetacodePatternText pattern => pattern.Pattern,
            _ => Expression(label, 0),
        };

        private static bool EndsWithJump(IReadOnlyList<MetacodeStatement> statements)
        {
            if (statements.Count == 0) return false;

            return statements[^1] switch
            {
                MetacodeBreak or MetacodeContinue or MetacodeReturn or MetacodeThrow or MetacodeGoto or MetacodeYield => true,
                MetacodeBlock block => EndsWithJump(block.Statements),
                _ => false,
            };
        }

        private void WriteTry(MetacodeTry @try)
        {
            Line("try");
            WriteBody(@try.Body);

            foreach (var @catch in @try.Catches)
            {
                var header = "catch";
                if (@catch.ExceptionType is not null || @catch.VariableName is not null)
                {
                    var inner = @catch.ExceptionType is null ? string.Empty : TypeName(@catch.ExceptionType);
                    if (@catch.VariableName is not null)
                        inner += (inner.Length > 0 ? " " : string.Empty) + Identifier(@catch.VariableName);
                    header += " (" + inner + ")";
                }

                if (@catch.Filter is not null)
                    header += " when (" + Expression(@catch.Filter, 0) + ")";

                Line(header);
                WriteBody(@catch.Body);
            }

            if (@try.Else is not null)
            {
                // Python's try/else runs when no exception was raised; C# has no such clause.
                Report("statement", "try/else has no C# clause; its block is written after the try", @try.Origin);
                Line("// TODO(metacode): the block below is the 'else' of a Python try (no exception raised)");
                WriteBody(@try.Else);
            }

            if (@try.Finally is not null)
            {
                Line("finally");
                WriteBody(@try.Finally);
            }
        }

        private void WriteUsing(MetacodeUsing @using)
        {
            string resource;
            if (@using.Declaration is not null)
            {
                var declaration = @using.Declaration;
                resource = TypeNameOr(declaration.Type, "var") + " " + Identifier(declaration.Name);
                if (declaration.Initializer is not null)
                    resource += " = " + Expression(declaration.Initializer, 0);
            }
            else
            {
                resource = @using.Resource is null ? string.Empty : Expression(@using.Resource, 0);
            }

            Line("using (" + resource + ")");
            WriteBody(@using.Body);
        }

        private void WriteOpaqueStatement(MetacodeOpaqueStatement opaque)
        {
            Report("statement", "kept verbatim: " + opaque.Reason, opaque.Origin);

            if (opaque.Language == MetacodeLanguage.CSharp)
            {
                foreach (var line in RawLines(opaque.Text))
                    Line(line);
                return;
            }

            Line("// TODO(metacode): " + PseudocodeText(opaque.Text) + " // " + opaque.Reason);
        }

        /// <summary>A statement written inside another one's header (<c>for (…; …; …)</c>).</summary>
        private string InlineStatement(MetacodeStatement? statement) => statement switch
        {
            null => string.Empty,
            MetacodeLocalVariable variable => LocalText(variable),
            MetacodeAssignment assignment => AssignmentText(assignment),
            MetacodeExpressionStatement expression => Expression(expression.Expression, 0),
            // Several declarators in a for-initializer must share one type in C#.
            MetacodeBlock block when block.Statements.Count > 0 && block.Statements.All(s => s is MetacodeLocalVariable) =>
                MergeDeclarators(block.Statements.Cast<MetacodeLocalVariable>().ToList()),
            _ => UnsupportedInline(statement),
        };

        private string UnsupportedInline(MetacodeStatement statement)
        {
            Report("statement", $"'{statement.GetType().Name}' cannot be written inside a for header", statement.Origin);
            return "/* unsupported */";
        }

        private string MergeDeclarators(IReadOnlyList<MetacodeLocalVariable> variables)
        {
            var first = variables[0];
            var type = TypeNameOr(first.Type, "var");
            var rest = variables.Skip(1).Select(variable =>
            {
                if (variable.Type is { } other && other.Render() != first.Type?.Render())
                    Report("statement", "several declarators share the first one's type", variable.Origin);
                return Identifier(variable.Name)
                       + (variable.Initializer is null ? string.Empty : " = " + Expression(variable.Initializer, 0));
            });

            return type + " " + string.Join(", ", new[] { Identifier(first.Name) }.Concat(rest));
        }

        private string LocalText(MetacodeLocalVariable variable)
        {
            var type = TypeNameOr(variable.Type, "var");

            // `const var` is not C#: a declaration whose type is not written loses the constant.
            var prefix = string.Empty;
            if (variable.IsConstant)
            {
                if (variable.Type is null or { IsDynamic: true })
                    Report("statement", $"const '{variable.Name}' has no type; written as a plain local", variable.Origin);
                else
                    prefix = "const ";
            }

            return prefix + type + " " + Identifier(variable.Name)
                   + (variable.Initializer is null ? string.Empty : " = " + Expression(variable.Initializer, 0));
        }

        private string AssignmentText(MetacodeAssignment assignment)
        {
            var target = Expression(assignment.Target, 17);
            var value = Expression(assignment.Value, 0);

            return assignment.Operator switch
            {
                MetacodeAssignmentOperator.Power => PowerAssignment(target, value, assignment.Origin),
                _ => target + " " + AssignmentOperator(assignment.Operator) + " " + value,
            };
        }

        private string PowerAssignment(string target, string value, MetacodeOrigin origin)
        {
            Report("expression", "'**=' has no C# operator; written as an assignment from Math.Pow", origin);
            return target + " = System.Math.Pow(" + target + ", " + value + ")";
        }

        // ── expressions ────────────────────────────────────────────────────────────────

        private string Expression(MetacodeExpression expression, int minimumPrecedence)
        {
            var precedence = Precedence(expression);
            var parenthesize = precedence < minimumPrecedence;
            var body = ExpressionBody(expression);
            return parenthesize ? "(" + body + ")" : body;
        }

        private string ExpressionBody(MetacodeExpression expression) => expression switch
        {
            MetacodeLiteral literal => LiteralText(literal),
            MetacodeIdentifier identifier => Identifier(identifier.Name),
            MetacodeMemberAccess access => Expression(access.Target, 17)
                                            + (access.NullConditional ? "?." : ".") + Identifier(access.Member),
            MetacodeInvocation invocation => Expression(invocation.Callee, 17) + "("
                                              + string.Join(", ", invocation.ArgumentList.Select(Argument)) + ")",
            MetacodeBinary binary => BinaryText(binary),
            MetacodeUnary unary => UnaryText(unary),
            MetacodeConditional conditional => Expression(conditional.Condition, 4) + " ? "
                                               + Expression(conditional.WhenTrue, 4) + " : "
                                               + Expression(conditional.WhenFalse, 3),
            MetacodeIndex index => Expression(index.Target, 17) + "["
                                   + string.Join(", ", index.Indices.Select(i => Expression(i, 0))) + "]",
            MetacodeObjectCreation creation => ObjectCreationText(creation),
            MetacodeWithExpression withExpression => WithText(withExpression),
            MetacodeAnonymousObject anonymous => "new { " + string.Join(", ", anonymous.Members.Select(m =>
                Identifier(m.Name) + " = " + Expression(m.Value, 0))) + " }",
            MetacodePatternMatch match => Expression(match.Operand, 11) + " is " + match.Pattern,
            MetacodePatternText pattern => pattern.Pattern,
            MetacodeSpread spread => ".." + Expression(spread.Operand, 16),
            MetacodeNewArray array => NewArrayText(array),
            MetacodeCast cast => "(" + TypeName(cast.Type) + ")" + Expression(cast.Operand, 16),
            MetacodeTypeCheck check => TypeCheckText(check),
            MetacodeCollection collection => CollectionText(collection),
            MetacodeDictionary dictionary => DictionaryText(dictionary),
            MetacodeComprehension comprehension => ComprehensionText(comprehension),
            MetacodeLambda lambda => LambdaText(lambda),
            MetacodeAwait awaitExpression => "await " + Expression(awaitExpression.Operand, 16),
            MetacodeRange range => RangeText(range),
            MetacodeIndexFromEnd fromEnd => "^" + Expression(fromEnd.Operand, 16),
            MetacodeInterpolatedString interpolated => InterpolationText(interpolated),
            MetacodeAssignmentExpression assignment => AssignmentExpressionText(assignment),
            MetacodeTypeOf typeOf => "typeof(" + TypeName(typeOf.Type) + ")",
            MetacodeSwitchExpression switchExpression => SwitchExpressionText(switchExpression),
            MetacodeOpaqueExpression opaque => OpaqueExpressionText(opaque),
            _ => UnsupportedExpression(expression),
        };

        private string BinaryText(MetacodeBinary binary)
        {
            var precedence = Precedence(binary);
            var rightAssociative = binary.Operator is MetacodeBinaryOperator.Power or MetacodeBinaryOperator.NullCoalesce;

            var left = Expression(binary.Left, rightAssociative ? precedence + 1 : precedence);
            var right = Expression(binary.Right, rightAssociative ? precedence : precedence + 1);

            return binary.Operator switch
            {
                // C# has no power operator, and no integer-division operator.
                MetacodeBinaryOperator.Power => PowerCall(binary),
                MetacodeBinaryOperator.IntegerDivide => IntegerDivision(left, right, binary.Origin),
                // Python's `in`: the closest C# is Enumerable.Contains, written fully qualified so no using is needed.
                MetacodeBinaryOperator.Contains => "System.Linq.Enumerable.Contains(" + right + ", " + left + ")",
                MetacodeBinaryOperator.NotContains => "!System.Linq.Enumerable.Contains(" + right + ", " + left + ")",
                _ => left + " " + BinaryOperator(binary.Operator) + " " + right,
            };
        }

        private string PowerCall(MetacodeBinary binary)
        {
            Report("expression", "'**' has no C# operator; written as Math.Pow", binary.Origin);
            return "System.Math.Pow(" + Expression(binary.Left, 0) + ", " + Expression(binary.Right, 0) + ")";
        }

        private string IntegerDivision(string left, string right, MetacodeOrigin origin)
        {
            Report("expression", "integer division has no C# operator; written as '/'", origin);
            return left + " / " + right;
        }

        private string UnaryText(MetacodeUnary unary) => unary.Operator switch
        {
            MetacodeUnaryOperator.Not => "!" + Expression(unary.Operand, 16),
            MetacodeUnaryOperator.Negate => "-" + Expression(unary.Operand, 17),
            MetacodeUnaryOperator.Plus => "+" + Expression(unary.Operand, 16),
            MetacodeUnaryOperator.BitwiseNot => "~" + Expression(unary.Operand, 16),
            MetacodeUnaryOperator.Increment => unary.IsPostfix
                ? Expression(unary.Operand, 17) + "++"
                : "++" + Expression(unary.Operand, 17),
            MetacodeUnaryOperator.Decrement => unary.IsPostfix
                ? Expression(unary.Operand, 17) + "--"
                : "--" + Expression(unary.Operand, 17),
            MetacodeUnaryOperator.Dereference => "*" + Expression(unary.Operand, 17),
            MetacodeUnaryOperator.AddressOf => "&" + Expression(unary.Operand, 17),
            _ => Expression(unary.Operand, 16),
        };

        private string ObjectCreationText(MetacodeObjectCreation creation)
        {
            var text = new StringBuilder();

            // A target-typed `new()` carries no type of its own; the declaration around it does.
            text.Append(creation.Type.Name == "new" ? "new" : "new " + TypeName(creation.Type));
            text.Append('(')
                .Append(string.Join(", ", (creation.Arguments ?? Array.Empty<MetacodeArgument>()).Select(Argument)))
                .Append(')');

            if (creation.CollectionElements is { Count: > 0 })
                text.Append(" { ").Append(string.Join(", ", creation.CollectionElements.Select(e => Expression(e, 0)))).Append(" }");

            if (creation.MemberInitializers is { Count: > 0 })
                text.Append(" { ").Append(string.Join(", ", creation.MemberInitializers
                    .Select(m => Identifier(m.Name) + " = " + Expression(m.Value, 0)))).Append(" }");

            return text.ToString();
        }

        private string WithText(MetacodeWithExpression withExpression) =>
            Expression(withExpression.Target, 17) + " with { " + string.Join(", ", withExpression.Initializers.Select(m =>
                Identifier(m.Name) + " = " + Expression(m.Value, 0))) + " }";

        private string NewArrayText(MetacodeNewArray array)
        {
            var element = array.ElementType is null ? string.Empty : TypeName(array.ElementType);
            var sizes = array.Sizes ?? Array.Empty<MetacodeExpression>();
            var elements = array.Elements;

            if (sizes.Count > 0)
            {
                if (element.Length == 0)
                {
                    Report("expression", "an array creation without an element type; written as object[]", array.Origin);
                    element = "object";
                }

                var sized = "new " + element + "[" + string.Join(", ", sizes.Select(e => Expression(e, 0))) + "]";
                return elements is { Count: > 0 }
                    ? sized + " { " + string.Join(", ", elements.Select(e => Expression(e, 0))) + " }"
                    : sized;
            }

            if (elements is { Count: > 0 })
                return "new " + element + "[] { " + string.Join(", ", elements.Select(e => Expression(e, 0))) + " }";

            return "new " + (element.Length == 0 ? "object" : element) + "[0]";
        }

        private string TypeCheckText(MetacodeTypeCheck check)
        {
            var operand = Expression(check.Operand, 11);
            var type = TypeName(check.Type);

            switch (check.Kind)
            {
                case MetacodeTypeCheckKind.As:
                    return operand + " as " + type;

                case MetacodeTypeCheckKind.IsNot:
                    if (check.Binding is not null)
                        Report("expression", "a negated pattern cannot bind a name; the binding was dropped", check.Origin);
                    return operand + " is not " + type;

                default:
                    return operand + " is " + type + (check.Binding is null ? string.Empty : " " + Identifier(check.Binding));
            }
        }

        private string CollectionText(MetacodeCollection collection)
        {
            switch (collection.Kind)
            {
                case MetacodeCollectionKind.Tuple:
                    if (collection.Items.Count == 1)
                    {
                        Report("expression", "a one-element tuple is not a C# tuple literal; written as ValueTuple.Create", collection.Origin);
                        return "System.ValueTuple.Create(" + Expression(collection.Items[0], 0) + ")";
                    }

                    return "(" + string.Join(", ", collection.Items.Select(i => Expression(i, 0))) + ")";

                case MetacodeCollectionKind.Set:
                    Report("expression", "a set literal has no C# form; written as a HashSet<object>", collection.Origin);
                    return "new System.Collections.Generic.HashSet<object> { "
                           + string.Join(", ", collection.Items.Select(i => Expression(i, 0))) + " }";

                default:
                    // C# 12 collection expressions: valid where a collection is expected, and the shape
                    // the C# frontend lowers back into this node.
                    return "[" + string.Join(", ", collection.Items.Select(i => Expression(i, 0))) + "]";
            }
        }

        private string DictionaryText(MetacodeDictionary dictionary)
        {
            Report("expression", "a dictionary literal has no C# form; written as a Dictionary<object, object>", dictionary.Origin);
            return "new System.Collections.Generic.Dictionary<object, object> { "
                   + string.Join(", ", dictionary.Entries.Select(e =>
                       "{ " + Expression(e.Key, 0) + ", " + Expression(e.Value, 0) + " }")) + " }";
        }

        /// <summary>
        /// A comprehension becomes LINQ method calls: <c>xs.Where(x => p).Select(x => e)</c>. It is the
        /// one lowering here that produces code a reader would also have written, so it is worth the
        /// shape; a set adds <c>ToHashSet</c>, a dictionary <c>ToDictionary</c>. A comprehension with
        /// several <c>for</c> clauses stays unlowered and says so: the outer variable would go out of
        /// scope, and emitting code that cannot compile is worse than saying it was not done.
        /// </summary>
        private string ComprehensionText(MetacodeComprehension comprehension)
        {
            if (comprehension.Clauses.Count == 0 || comprehension.Clauses[0].Kind != MetacodeComprehensionClauseKind.For)
            {
                Report("expression", "a comprehension without a leading for cannot be lowered to LINQ", comprehension.Origin);
                return "[]";
            }

            if (comprehension.Clauses.Skip(1).Any(clause => clause.Kind == MetacodeComprehensionClauseKind.For))
            {
                Report("expression", "a comprehension with several for clauses cannot be lowered to LINQ; left empty", comprehension.Origin);
                return "[]";
            }

            var text = new StringBuilder(Expression(comprehension.Clauses[0].Expression, 0));
            var variable = FirstVariable(comprehension.Clauses[0].Targets);

            foreach (var clause in comprehension.Clauses.Skip(1))
                text.Append(".Where(").Append(variable).Append(" => ").Append(Expression(clause.Expression, 2)).Append(')');

            var projection = Expression(comprehension.Element, 2);

            return comprehension.Kind switch
            {
                MetacodeComprehensionKind.Set =>
                    text.Append(".Select(").Append(variable).Append(" => ").Append(projection).Append(").ToHashSet()").ToString(),
                MetacodeComprehensionKind.Dictionary when comprehension.Value is not null =>
                    text.Append(".ToDictionary(").Append(variable).Append(" => ").Append(projection)
                        .Append(", ").Append(variable).Append(" => ").Append(Expression(comprehension.Value, 2)).Append(')').ToString(),
                _ =>
                    text.Append(".Select(").Append(variable).Append(" => ").Append(projection).Append(')').ToString(),
            };
        }

        private static string FirstVariable(IReadOnlyList<string> targets) =>
            targets.Count > 0 ? Identifier(targets[0]) : "item";

        private string LambdaText(MetacodeLambda lambda)
        {
            var parameters = string.Join(", ", (lambda.Parameters ?? Array.Empty<MetacodeParameter>())
                .Select(p => (p.Type is null or { IsDynamic: true } ? string.Empty : TypeName(p.Type) + " ") + Identifier(p.Name)));

            // The model has no async flag on a lambda, and C# needs `async` for an `await` inside one.
            // An over-applied `async` only costs a warning, so a body that awaits anywhere gets it.
            var isAsync = AwaitFinder.Contains(lambda.Body) || (lambda.Expression is not null && AwaitFinder.Contains(lambda.Expression));
            var header = (isAsync ? "async " : string.Empty) + "(" + parameters + ") => ";

            if (lambda.Expression is not null)
                return header + Expression(lambda.Expression, 2);

            if (lambda.Body is null || lambda.Body.Statements.Count == 0)
                return header + "{ }";

            // A block-bodied lambda is written through the same statement writer, into a buffer of its
            // own at one more indentation level, then returned as one expression.
            var saved = _text.Length;
            var statements = new StringBuilder();
            _depth++;
            foreach (var statement in lambda.Body.Statements)
                WriteStatement(statement);
            statements.Append(_text.ToString(saved, _text.Length - saved));
            _text.Length = saved;
            _depth--;

            return header + "{" + _options.NewLine + statements + Indent() + "}";
        }

        private string RangeText(MetacodeRange range)
        {
            if (range.Step is not null)
                Report("expression", "a range with a step has no C# form; the step was dropped", range.Origin);

            return (range.Start is null ? string.Empty : Expression(range.Start, 0))
                   + ".."
                   + (range.End is null ? string.Empty : Expression(range.End, 0));
        }

        private string InterpolationText(MetacodeInterpolatedString interpolated)
        {
            var text = new StringBuilder("$\"");
            foreach (var part in interpolated.Parts)
            {
                if (part.Text is not null)
                {
                    text.Append(part.Text
                        .Replace("\\", "\\\\")
                        .Replace("\"", "\\\"")
                        .Replace("\n", "\\n")
                        .Replace("{", "{{")
                        .Replace("}", "}}"));
                }
                else if (part.Expression is not null)
                {
                    text.Append('{').Append(Expression(part.Expression, 0)).Append('}');
                }
            }

            return text.Append('"').ToString();
        }

        private string AssignmentExpressionText(MetacodeAssignmentExpression assignment)
        {
            var target = Expression(assignment.Target, 17);
            var value = Expression(assignment.Value, 1);

            return assignment.Operator switch
            {
                MetacodeAssignmentOperator.Power => PowerAssignment(target, value, assignment.Origin),
                _ => target + " " + AssignmentOperator(assignment.Operator) + " " + value,
            };
        }

        private string SwitchExpressionText(MetacodeSwitchExpression switchExpression)
        {
            var arms = switchExpression.Arms.Select(arm =>
                arm.Pattern
                + (arm.Guard is null ? string.Empty : " when " + Expression(arm.Guard, 0))
                + " => " + Expression(arm.Value, 0));

            return Expression(switchExpression.Subject, 17) + " switch { " + string.Join(", ", arms) + " }";
        }

        private string OpaqueExpressionText(MetacodeOpaqueExpression opaque)
        {
            if (opaque.Language == MetacodeLanguage.CSharp)
            {
                // The text is the source's own expression: valid C#, but it may be a compound one, so
                // it is parenthesized where it sits inside another expression.
                return "(" + opaque.Text + ")";
            }

            Report("expression", "kept as default: " + opaque.Reason, opaque.Origin);
            return "default!";
        }

        private string UnsupportedExpression(MetacodeExpression expression)
        {
            Report("expression", $"unmodelled expression {expression.GetType().Name}", expression.Origin);
            return "default!";
        }

        // ── names, types, literals ─────────────────────────────────────────────────────

        private string Parameter(MetacodeParameter parameter)
        {
            var prefix = parameter.Kind switch
            {
                MetacodeParameterKind.Ref => "ref ",
                MetacodeParameterKind.Out => "out ",
                MetacodeParameterKind.In => "in ",
                MetacodeParameterKind.Params => "params ",
                // Python's keyword-only marker has no C# form.
                _ => string.Empty,
            };

            var text = prefix + TypeNameOr(parameter.Type, "object") + " " + Identifier(parameter.Name);
            if (parameter.DefaultValue is not null)
                text += " = " + Expression(parameter.DefaultValue, 0);
            return text;
        }

        private string Argument(MetacodeArgument argument)
        {
            var prefix = argument.Kind switch
            {
                MetacodeParameterKind.Ref => "ref ",
                MetacodeParameterKind.Out => "out ",
                MetacodeParameterKind.In => "in ",
                _ => string.Empty,
            };

            return prefix + (argument.Name is null ? string.Empty : Identifier(argument.Name) + ": ")
                   + Expression(argument.Value, 0);
        }

        /// <summary>The type as written. Null and <c>dynamic</c> have no name of their own.</summary>
        private static string TypeName(MetacodeTypeRef? type)
        {
            if (type is null || type.IsDynamic) return string.Empty;

            var text = type.IsReference ? "ref " : string.Empty;
            text += type.Name;
            if (type.Arguments.Count > 0)
                text += "<" + string.Join(", ", type.Arguments.Select(TypeName)) + ">";
            if (type.IsArray) text += "[]";
            if (type.IsPointer) text += "*";
            if (type.IsNullable) text += "?";
            return text;
        }

        /// <summary>Same, but a declaration that needs a written type (a field, a parameter) gets a fallback.</summary>
        private static string TypeNameOr(MetacodeTypeRef? type, string fallback)
        {
            var name = TypeName(type);
            return name.Length == 0 ? fallback : name;
        }

        private static string LiteralText(MetacodeLiteral literal) => literal.Kind switch
        {
            MetacodeLiteralKind.String when !LooksQuoted(literal.Text, "\"", "@\"", "$\"", "$$\"") =>
                "\"" + Escape(literal.Text) + "\"",
            MetacodeLiteralKind.Character when !LooksQuoted(literal.Text, "'") =>
                "'" + Escape(literal.Text) + "'",
            _ => literal.Text,
        };

        private static bool LooksQuoted(string text, params string[] prefixes) =>
            prefixes.Any(prefix => text.StartsWith(prefix, StringComparison.Ordinal));

        private static string Escape(string text) => text
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\n", "\\n")
            .Replace("\r", "\\r")
            .Replace("\t", "\\t");

        /// <summary>
        /// A name as C# accepts it: a keyword becomes <c>@keyword</c>, a compound name the model kept as
        /// text (<c>operator +</c>, <c>List&lt;int&gt;</c>) is written as it is.
        /// </summary>
        private static string Identifier(string name)
        {
            if (name.Length == 0) return name;

            if (SyntaxFacts.IsValidIdentifier(name))
                return SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

            return name;
        }

        private static string Modifiers(MetacodeModifiers modifiers, bool isField = false, bool hasType = true)
        {
            if (modifiers == MetacodeModifiers.None) return string.Empty;

            var parts = new List<string>(6);
            Add(MetacodeModifiers.Public, "public");
            Add(MetacodeModifiers.Protected, "protected");
            Add(MetacodeModifiers.Internal, "internal");
            Add(MetacodeModifiers.Private, "private");
            Add(MetacodeModifiers.New, "new");

            // A const field is implicitly static and cannot be readonly.
            var isConst = isField && modifiers.HasFlag(MetacodeModifiers.Const) && hasType;
            if (!isConst) Add(MetacodeModifiers.Static, "static");

            Add(MetacodeModifiers.Abstract, "abstract");
            Add(MetacodeModifiers.Virtual, "virtual");
            Add(MetacodeModifiers.Override, "override");
            Add(MetacodeModifiers.Sealed, "sealed");

            if (isConst) parts.Add("const");
            else Add(MetacodeModifiers.ReadOnly, "readonly");

            Add(MetacodeModifiers.Async, "async");
            Add(MetacodeModifiers.Partial, "partial");
            Add(MetacodeModifiers.Extern, "extern");
            Add(MetacodeModifiers.Unsafe, "unsafe");

            return parts.Count == 0 ? string.Empty : string.Join(" ", parts) + " ";

            void Add(MetacodeModifiers flag, string text)
            {
                if (modifiers.HasFlag(flag)) parts.Add(text);
            }
        }

        private static bool Has(MetacodeModifiers modifiers, MetacodeModifiers flag) => modifiers.HasFlag(flag);

        /// <summary>
        /// Whether a subtree contains <c>await</c>. It descends into nested lambdas too: an outer lambda
        /// marked <c>async</c> without awaiting is a warning, one that awaits without it is an error.
        /// </summary>
        private static class AwaitFinder
        {
            public static bool Contains(MetacodeBlock? block) => block is not null && block.Statements.Any(Contains);

            public static bool Contains(MetacodeStatement? statement) => statement switch
            {
                null or MetacodeBreak or MetacodeContinue or MetacodeGoto or MetacodeComment or MetacodeOpaqueStatement
                    or MetacodeImport => false,
                MetacodeBlock block => block.Statements.Any(Contains),
                MetacodeLocalVariable variable => Contains(variable.Initializer),
                MetacodeAssignment assignment => Contains(assignment.Target) || Contains(assignment.Value),
                MetacodeExpressionStatement expression => Contains(expression.Expression),
                MetacodeReturn @return => Contains(@return.Value),
                MetacodeThrow @throw => Contains(@throw.Exception),
                MetacodeYield @yield => Contains(@yield.Value),
                MetacodeIf @if => Contains(@if.Condition) || Contains(@if.Then) || Contains(@if.Else),
                MetacodeWhile @while => Contains(@while.Condition) || Contains(@while.Body),
                MetacodeDoWhile doWhile => Contains(doWhile.Body) || Contains(doWhile.Condition),
                MetacodeForEach forEach => Contains(forEach.Iterable) || Contains(forEach.Body),
                MetacodeFor @for => Contains(@for.Initializer) || Contains(@for.Condition)
                                    || Contains(@for.Increment) || Contains(@for.Body),
                MetacodeSwitch @switch => Contains(@switch.Subject) || @switch.Cases.Any(@case => Contains(@case.Body)),
                MetacodeLabel label => Contains(label.Statement),
                MetacodeTry @try => Contains(@try.Body) || Contains(@try.Finally) || Contains(@try.Else)
                                    || @try.Catches.Any(@catch => Contains(@catch.Body) || Contains(@catch.Filter)),
                MetacodeUsing @using => Contains(@using.Resource) || Contains(@using.Declaration?.Initializer)
                                        || Contains(@using.Body),
                MetacodeLock @lock => Contains(@lock.Target) || Contains(@lock.Body),
                MetacodeLocalFunction local => Contains(local.Function.Body),
                _ => false,
            };

            public static bool Contains(MetacodeExpression? expression) => expression switch
            {
                null or MetacodeLiteral or MetacodeIdentifier or MetacodeTypeOf or MetacodeOpaqueExpression => false,
                MetacodeAwait => true,
                MetacodeMemberAccess access => Contains(access.Target),
                MetacodeInvocation invocation => Contains(invocation.Callee)
                                                 || invocation.ArgumentList.Any(argument => Contains(argument.Value)),
                MetacodeBinary binary => Contains(binary.Left) || Contains(binary.Right),
                MetacodeUnary unary => Contains(unary.Operand),
                MetacodeConditional conditional => Contains(conditional.Condition) || Contains(conditional.WhenTrue)
                                                   || Contains(conditional.WhenFalse),
                MetacodeIndex index => Contains(index.Target) || index.Indices.Any(Contains),
                MetacodeObjectCreation creation => (creation.Arguments ?? Array.Empty<MetacodeArgument>()).Any(a => Contains(a.Value))
                                                   || (creation.CollectionElements ?? Array.Empty<MetacodeExpression>()).Any(Contains)
                                                   || (creation.MemberInitializers ?? Array.Empty<MetacodeMemberInitializer>())
                                                       .Any(initializer => Contains(initializer.Value)),
                MetacodeNewArray array => (array.Sizes ?? Array.Empty<MetacodeExpression>()).Any(Contains)
                                          || (array.Elements ?? Array.Empty<MetacodeExpression>()).Any(Contains),
                MetacodeCast cast => Contains(cast.Operand),
                MetacodeTypeCheck check => Contains(check.Operand),
                MetacodeCollection collection => collection.Items.Any(Contains),
                MetacodeDictionary dictionary => dictionary.Entries.Any(entry => Contains(entry.Key) || Contains(entry.Value)),
                MetacodeComprehension comprehension => comprehension.Clauses.Any(clause => Contains(clause.Expression))
                                                       || Contains(comprehension.Element) || Contains(comprehension.Value),
                MetacodeLambda lambda => Contains(lambda.Expression) || Contains(lambda.Body),
                MetacodeRange range => Contains(range.Start) || Contains(range.End) || Contains(range.Step),
                MetacodeIndexFromEnd fromEnd => Contains(fromEnd.Operand),
                MetacodeInterpolatedString interpolated => interpolated.Parts.Any(part => Contains(part.Expression)),
                MetacodeAssignmentExpression assignment => Contains(assignment.Target) || Contains(assignment.Value),
                MetacodeSwitchExpression switchExpression => Contains(switchExpression.Subject)
                                                             || switchExpression.Arms.Any(arm => Contains(arm.Guard)
                                                                 || Contains(arm.Value)),
                _ => false,
            };
        }

        private static string ImportText(MetacodeImport import)
        {
            var names = string.Join(", ", import.NameList.Select(n => n.Alias is null ? n.Name : n.Name + " as " + n.Alias));
            return import.IsFrom ? import.Module + "." + names : names;
        }

        // ── emission helpers ───────────────────────────────────────────────────────────

        private void WriteBody(MetacodeBlock block)
        {
            Open();
            WriteStatements(block.Statements);
            Close();
        }

        private void Open()
        {
            Line("{");
            _depth++;
        }

        private void Close()
        {
            _depth--;
            Line("}");
        }

        private void Blank() => _text.Append(_options.NewLine);

        private void Line(string content) => _text.Append(Indent()).Append(content).Append(_options.NewLine);

        /// <summary>Appends to the line just written — <c>} while (c);</c>, <c>} = 5;</c>.</summary>
        private void SetLineTail(string tail)
        {
            TrimTrailingNewLine();
            _text.Append(tail).Append(_options.NewLine);
        }

        private void TrimTrailingNewLine()
        {
            if (_text.Length >= _options.NewLine.Length
                && _text.ToString(_text.Length - _options.NewLine.Length, _options.NewLine.Length) == _options.NewLine)
                _text.Length -= _options.NewLine.Length;
        }

        private string Indent() => string.Concat(Enumerable.Repeat(_options.Indent, _depth));

        private static IEnumerable<string> RawLines(string text) =>
            text.Replace("\r", string.Empty).Split('\n');

        private static string PseudocodeText(string text) =>
            text.Replace("\r", string.Empty).Replace("\n", "\\n");

        private static int Precedence(MetacodeExpression expression) => expression switch
        {
            MetacodeAssignmentExpression => 1,
            MetacodeLambda => 2,
            MetacodeConditional => 3,
            MetacodeBinary binary => binary.Operator switch
            {
                MetacodeBinaryOperator.NullCoalesce => 4,
                MetacodeBinaryOperator.LogicalOr => 5,
                MetacodeBinaryOperator.LogicalAnd => 6,
                MetacodeBinaryOperator.BitwiseOr => 7,
                MetacodeBinaryOperator.BitwiseXor => 8,
                MetacodeBinaryOperator.BitwiseAnd => 9,
                MetacodeBinaryOperator.Equal or MetacodeBinaryOperator.NotEqual
                    or MetacodeBinaryOperator.Contains or MetacodeBinaryOperator.NotContains => 10,
                MetacodeBinaryOperator.LessThan or MetacodeBinaryOperator.LessThanOrEqual
                    or MetacodeBinaryOperator.GreaterThan or MetacodeBinaryOperator.GreaterThanOrEqual => 11,
                MetacodeBinaryOperator.ShiftLeft or MetacodeBinaryOperator.ShiftRight => 12,
                MetacodeBinaryOperator.Add or MetacodeBinaryOperator.Subtract => 13,
                MetacodeBinaryOperator.Multiply or MetacodeBinaryOperator.Divide
                    or MetacodeBinaryOperator.IntegerDivide or MetacodeBinaryOperator.Modulo => 14,
                MetacodeBinaryOperator.Power => 17,
                _ => 13,
            },
            MetacodeTypeCheck or MetacodePatternMatch => 11,
            MetacodeUnary or MetacodeAwait or MetacodeCast or MetacodeSpread => 16,
            _ => 17,
        };

        private static string BinaryOperator(MetacodeBinaryOperator @operator) => @operator switch
        {
            MetacodeBinaryOperator.Add => "+",
            MetacodeBinaryOperator.Subtract => "-",
            MetacodeBinaryOperator.Multiply => "*",
            MetacodeBinaryOperator.Divide => "/",
            MetacodeBinaryOperator.IntegerDivide => "/",
            MetacodeBinaryOperator.Modulo => "%",
            MetacodeBinaryOperator.Equal => "==",
            MetacodeBinaryOperator.NotEqual => "!=",
            MetacodeBinaryOperator.LessThan => "<",
            MetacodeBinaryOperator.LessThanOrEqual => "<=",
            MetacodeBinaryOperator.GreaterThan => ">",
            MetacodeBinaryOperator.GreaterThanOrEqual => ">=",
            MetacodeBinaryOperator.LogicalAnd => "&&",
            MetacodeBinaryOperator.LogicalOr => "||",
            MetacodeBinaryOperator.BitwiseAnd => "&",
            MetacodeBinaryOperator.BitwiseOr => "|",
            MetacodeBinaryOperator.BitwiseXor => "^",
            MetacodeBinaryOperator.ShiftLeft => "<<",
            MetacodeBinaryOperator.ShiftRight => ">>",
            MetacodeBinaryOperator.NullCoalesce => "??",
            _ => "+",
        };

        private static string AssignmentOperator(MetacodeAssignmentOperator @operator) => @operator switch
        {
            MetacodeAssignmentOperator.Assign => "=",
            MetacodeAssignmentOperator.Add => "+=",
            MetacodeAssignmentOperator.Subtract => "-=",
            MetacodeAssignmentOperator.Multiply => "*=",
            MetacodeAssignmentOperator.Divide => "/=",
            MetacodeAssignmentOperator.Modulo => "%=",
            MetacodeAssignmentOperator.BitwiseAnd => "&=",
            MetacodeAssignmentOperator.BitwiseOr => "|=",
            MetacodeAssignmentOperator.BitwiseXor => "^=",
            MetacodeAssignmentOperator.ShiftLeft => "<<=",
            MetacodeAssignmentOperator.ShiftRight => ">>=",
            MetacodeAssignmentOperator.Coalesce => "??=",
            _ => "=",
        };
    }
