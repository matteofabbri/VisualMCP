using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;

// RS1036/RS1038/RS1041/RS2008 describe a *compiler extension* (an analyzer package shipped to
// consumer builds, targeting netstandard2.0, with release tracking). This analyzer is neither: it is
// compiled into the server and run in-process through Compilation.WithAnalyzers, the same way
// InspectionPackCatalog runs the external packs. The packaging rules do not apply.
#pragma warning disable RS1036, RS1038, RS1041, RS2008

namespace Snitch.Languages.CSharp.Inspections;

/// <summary>
/// VMC0001 — the house rule "one type per file": a file declares a single top-level class, struct,
/// interface, record, enum or delegate. It is what the server itself follows (CLAUDE_PROJECT_RULES.md)
/// and what <c>inspect_code</c> reports for any solution through the in-process "house" pack.
/// Nested types belong to their container and are not counted; generated files are skipped because
/// their shape is not the author's.
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class OneTypePerFileAnalyzer : DiagnosticAnalyzer
{
    public const string RuleId = "VMC0001";

    private static readonly DiagnosticDescriptor Rule = new(
        RuleId,
        title: "One type per file",
        messageFormat: "File declares {0} top-level types ({1}); give each type its own file",
        category: "Style",
        defaultSeverity: DiagnosticSeverity.Info,
        isEnabledByDefault: true,
        description: "A file holds exactly one top-level type. Nested types are part of their container and are not counted.");

    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => ImmutableArray.Create(Rule);

    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.None);
        context.EnableConcurrentExecution();
        context.RegisterSyntaxTreeAction(AnalyzeTree);
    }

    private static void AnalyzeTree(SyntaxTreeAnalysisContext context)
    {
        var root = (CompilationUnitSyntax)context.Tree.GetRoot(context.CancellationToken);
        if (IsGenerated(context.Tree, root)) return;

        var declarations = new List<(string Name, SyntaxToken Identifier)>();
        Collect(root.Members, string.Empty, declarations);

        // Two partial declarations of the same type in one file are one type, not two.
        var types = declarations
            .GroupBy(declaration => declaration.Name, StringComparer.Ordinal)
            .Select(group => group.First())
            .ToList();

        if (types.Count <= 1) return;

        var names = string.Join(", ", types.Select(type => type.Name));
        foreach (var (_, identifier) in types.Skip(1))
            context.ReportDiagnostic(Diagnostic.Create(Rule, identifier.GetLocation(), types.Count, names));
    }

    private static void Collect(
        SyntaxList<MemberDeclarationSyntax> members, string namespacePrefix, List<(string, SyntaxToken)> declarations)
    {
        foreach (var member in members)
        {
            switch (member)
            {
                case BaseNamespaceDeclarationSyntax @namespace:
                    Collect(@namespace.Members, namespacePrefix + @namespace.Name + ".", declarations);
                    break;

                case BaseTypeDeclarationSyntax type:
                    declarations.Add((namespacePrefix + type.Identifier.ValueText, type.Identifier));
                    break;

                case DelegateDeclarationSyntax @delegate:
                    declarations.Add((namespacePrefix + @delegate.Identifier.ValueText, @delegate.Identifier));
                    break;
            }
        }
    }

    private static bool IsGenerated(SyntaxTree tree, CompilationUnitSyntax root)
    {
        var fileName = Path.GetFileName(tree.FilePath);
        if (fileName.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) ||
            fileName.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase) ||
            fileName.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase) ||
            fileName.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase) ||
            fileName.EndsWith(".AssemblyInfo.cs", StringComparison.OrdinalIgnoreCase))
            return true;

        var header = root.GetLeadingTrivia().ToFullString();
        return header.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase) ||
               header.Contains("<autogenerated", StringComparison.OrdinalIgnoreCase);
    }
}
