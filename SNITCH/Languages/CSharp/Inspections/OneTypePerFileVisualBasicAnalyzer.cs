using System.Collections.Immutable;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.VisualBasic;
using Microsoft.CodeAnalysis.VisualBasic.Syntax;

// See OneTypePerFileAnalyzer: this is an in-process house rule, not an analyzer package shipped to
// consumer builds, so the packaging rules (RS1036/RS1038/RS1041/RS2008) do not apply to it.
// RS1019 wants one analyzer per diagnostic id in a compilation; VMC0001 is one rule with one
// implementation per language (Roslyn's own CA rules do the same), which is what makes the id mean
// the same thing in a C# and in a VB project.
#pragma warning disable RS1019, RS1036, RS1038, RS1041, RS2008

namespace Snitch.Languages.CSharp.Inspections;

/// <summary>
/// VMC0001 for Visual Basic — the same house rule as <see cref="OneTypePerFileAnalyzer"/>, read from
/// VB syntax: a file declares a single top-level class, module, structure, interface, enum or
/// delegate. Nested types belong to their container and are not counted, and generated files are
/// skipped because their shape is not the author's.
/// </summary>
[DiagnosticAnalyzer(LanguageNames.VisualBasic)]
public sealed class OneTypePerFileVisualBasicAnalyzer : DiagnosticAnalyzer
{
    public const string RuleId = OneTypePerFileAnalyzer.RuleId;

    private static readonly DiagnosticDescriptor Rule = new(
        RuleId,
        title: "One type per file",
        messageFormat: "File declares {0} top-level types ({1}); give each type its own file",
        category: "Style",
        defaultSeverity: DiagnosticSeverity.Info,
        isEnabledByDefault: true,
        description: "A file holds exactly one top-level type. Nested types are part of their container and are not counted.");

    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => ImmutableArray.Create(Rule);

    public override void Initialize(AnalysisContext context)
    {
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.None);
        context.EnableConcurrentExecution();
        context.RegisterSyntaxTreeAction(AnalyzeTree);
    }

    private static void AnalyzeTree(SyntaxTreeAnalysisContext context)
    {
        var root = (CompilationUnitSyntax)context.Tree.GetRoot(context.CancellationToken);
        if (IsGenerated(context.Tree, root)) return;

        var declarations = new List<(string Name, SyntaxToken Identifier)>();
        Collect(root.Members, string.Empty, declarations);

        // Two partial declarations of the same type in one file are one type, not two. VB compares
        // type names case-insensitively, so the grouping does too.
        var types = declarations
            .GroupBy(declaration => declaration.Name, StringComparer.OrdinalIgnoreCase)
            .Select(group => group.First())
            .ToList();

        if (types.Count <= 1) return;

        var names = string.Join(", ", types.Select(type => type.Name));
        foreach (var (_, identifier) in types.Skip(1))
            context.ReportDiagnostic(Diagnostic.Create(Rule, identifier.GetLocation(), types.Count, names));
    }

    private static void Collect(
        SyntaxList<StatementSyntax> members, string namespacePrefix, List<(string, SyntaxToken)> declarations)
    {
        foreach (var member in members)
        {
            switch (member)
            {
                case NamespaceBlockSyntax @namespace:
                    Collect(@namespace.Members, namespacePrefix + @namespace.NamespaceStatement.Name + ".", declarations);
                    break;

                case TypeBlockSyntax type:
                    declarations.Add((namespacePrefix + type.BlockStatement.Identifier.ValueText, type.BlockStatement.Identifier));
                    break;

                case EnumBlockSyntax enumeration:
                    declarations.Add((namespacePrefix + enumeration.EnumStatement.Identifier.ValueText, enumeration.EnumStatement.Identifier));
                    break;

                case DelegateStatementSyntax @delegate:
                    declarations.Add((namespacePrefix + @delegate.Identifier.ValueText, @delegate.Identifier));
                    break;
            }
        }
    }

    private static bool IsGenerated(SyntaxTree tree, CompilationUnitSyntax root)
    {
        var fileName = Path.GetFileName(tree.FilePath);
        if (fileName.EndsWith(".Designer.vb", StringComparison.OrdinalIgnoreCase) ||
            fileName.EndsWith(".g.vb", StringComparison.OrdinalIgnoreCase) ||
            fileName.EndsWith(".generated.vb", StringComparison.OrdinalIgnoreCase) ||
            fileName.EndsWith(".AssemblyInfo.vb", StringComparison.OrdinalIgnoreCase))
            return true;

        var header = root.GetLeadingTrivia().ToFullString();
        return header.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase) ||
               header.Contains("<autogenerated", StringComparison.OrdinalIgnoreCase);
    }
}
