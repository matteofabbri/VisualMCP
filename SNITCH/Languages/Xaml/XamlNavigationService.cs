using Snitch.Workspace;

namespace Snitch.Languages.Xaml;

/// <summary>
/// Navigation for XAML, the half a markup scanner usually lacks: an x:Name and the field the
/// generator creates for it, a resource key and every place it is defined and used, a style and its
/// BasedOn chain, an event handler and the method behind it.
/// </summary>
public interface IXamlNavigationService
{
    Task<object> NavigateAsync(string action, string name, string? projectName, string? path, int maxResults);
}

public sealed class XamlNavigationService : IXamlNavigationService
{
    private readonly IRoslynWorkspace _workspace;
    public XamlNavigationService(IRoslynWorkspace workspace) => _workspace = workspace;

    public async Task<object> NavigateAsync(string action, string name, string? projectName = null,
        string? path = null, int maxResults = 200)
    {
        var kind = (action ?? string.Empty).Trim().ToLowerInvariant();
        if (kind is not ("name" or "resource" or "style" or "handler"))
            return new
            {
                error = $"Unknown action '{action}'. Use one of: name (x:Name <-> code-behind field), " +
                        "resource (x:Key definitions and uses), style (BasedOn chain), handler (event handler <-> method).",
            };

        if (string.IsNullOrWhiteSpace(name))
            return new { error = "A name is required (the x:Name, the resource key, the style key or the handler method)." };

        maxResults = XamlAnalysis.Clamp(maxResults, 200, 2000);

        var collection = await XamlAnalysis.CollectAsync(_workspace, projectName, path, 5000);
        if (collection.Error is not null) return new { error = collection.Error };

        var documents = new List<XamlDocument>();
        foreach (var file in collection.Files)
        {
            var document = XamlAnalysis.TryRead(file, collection, []);
            if (document is not null) documents.Add(document);
        }

        var solution = await _workspace.EnsureSolutionLoadedAsync();

        return kind switch
        {
            "name" => await ByNameAsync(documents, solution, name.Trim(), maxResults),
            "resource" => ByKey(documents, name.Trim(), maxResults),
            "style" => ByStyle(documents, name.Trim(), maxResults),
            _ => await ByHandlerAsync(documents, solution, name.Trim(), maxResults),
        };
    }

    private static async Task<object> ByNameAsync(List<XamlDocument> documents, Microsoft.CodeAnalysis.Solution? solution,
        string name, int maxResults)
    {
        var definitions = documents
            .SelectMany(document => document.Names
                .Where(declared => declared.Name == name)
                .Select(declared => new
                {
                    file = document.FilePath,
                    relativePath = document.RelativePath,
                    line = declared.Line,
                    className = document.ClassName,
                }))
            .Take(maxResults)
            .ToList();

        var uses = documents
            .SelectMany(document => document.NameReferences
                .Where(reference => reference.Name == name)
                .Select(reference => new
                {
                    file = document.FilePath,
                    relativePath = document.RelativePath,
                    line = reference.Line,
                    kind = reference.Kind,
                }))
            .Take(maxResults)
            .ToList();

        var generated = new List<object>();
        foreach (var document in documents.Where(document => document.Names.Any(declared => declared.Name == name)))
        {
            if (solution is null || document.ClassName is null) continue;

            var facts = await XamlAnalysis.ResolveTypeAsync(solution, document.Project, document.ClassName);
            if (facts is null) continue;

            generated.Add(new
            {
                type = facts.FullName,
                file = facts.FilePath,
                line = facts.Line,
                hasDeclaredMember = facts.DeclaredMemberNames.Contains(name),
                note = facts.DeclaredMemberNames.Contains(name)
                    ? "The code-behind also declares a member with this name (XAML0007)."
                    : "The field is generated by the XAML compiler from x:Name.",
            });
        }

        return new
        {
            action = "name",
            name,
            definitionCount = definitions.Count,
            useCount = uses.Count,
            definitions,
            uses,
            codeBehind = generated,
            note = "A binding by ElementName resolves to the element that declares the x:Name; the generated " +
                   "field is the code-behind's way to reach the same element.",
        };
    }

    private static object ByKey(List<XamlDocument> documents, string key, int maxResults)
    {
        var definitions = documents
            .SelectMany(document => document.Keys
                .Where(declared => declared.Key == key)
                .Select(declared => new
                {
                    file = document.FilePath,
                    relativePath = document.RelativePath,
                    line = declared.Line,
                    owner = declared.Owner,
                }))
            .Take(maxResults)
            .ToList();

        var uses = documents
            .SelectMany(document => document.ResourceReferences
                .Where(reference => reference.Key == key)
                .Select(reference => new
                {
                    file = document.FilePath,
                    relativePath = document.RelativePath,
                    line = reference.Line,
                    kind = reference.Kind,
                }))
            .Take(maxResults)
            .ToList();

        return new
        {
            action = "resource",
            key,
            definitionCount = definitions.Count,
            useCount = uses.Count,
            definitions,
            uses,
            note = definitions.Count == 0
                ? "No x:Key with that name in the scanned files: it may come from a theme dictionary in a referenced assembly."
                : null,
        };
    }

    private static object ByStyle(List<XamlDocument> documents, string key, int maxResults)
    {
        var definitions = documents
            .SelectMany(document => document.Styles
                .Where(style => style.Key == key)
                .Select(style => new
                {
                    file = document.FilePath,
                    relativePath = document.RelativePath,
                    line = style.Line,
                    basedOn = style.BasedOnKey,
                }))
            .Take(maxResults)
            .ToList();

        var chain = new List<object>();
        var basedOnByKey = documents
            .SelectMany(document => document.Styles)
            .GroupBy(style => style.Key, StringComparer.Ordinal)
            .ToDictionary(group => group.Key, group => group.First().BasedOnKey, StringComparer.Ordinal);

        var current = key;
        var seen = new HashSet<string>(StringComparer.Ordinal) { key };
        while (current is not null && basedOnByKey.TryGetValue(current, out var parent) && chain.Count < 20)
        {
            chain.Add(new { key = current, basedOn = parent });
            if (parent is null || !seen.Add(parent)) break;
            current = parent;
        }

        var derived = documents
            .SelectMany(document => document.Styles
                .Where(style => style.BasedOnKey == key)
                .Select(style => new
                {
                    file = document.FilePath,
                    key = style.Key,
                    line = style.Line,
                }))
            .Take(maxResults)
            .ToList();

        return new
        {
            action = "style",
            key,
            definitionCount = definitions.Count,
            definitions,
            basedOnChain = chain,
            derivedStyles = derived,
        };
    }

    private static async Task<object> ByHandlerAsync(List<XamlDocument> documents,
        Microsoft.CodeAnalysis.Solution? solution, string method, int maxResults)
    {
        var references = documents
            .SelectMany(document => document.Handlers
                .Where(handler => handler.Method.Split('.').Last() == method)
                .Select(handler => new
                {
                    file = document.FilePath,
                    relativePath = document.RelativePath,
                    line = handler.Line,
                    attribute = handler.Attribute,
                    className = document.ClassName,
                }))
            .Take(maxResults)
            .ToList();

        var methods = new List<object>();
        foreach (var document in documents.Where(document =>
                     document.Handlers.Any(handler => handler.Method.Split('.').Last() == method)))
        {
            if (solution is null || document.ClassName is null) continue;

            var facts = await XamlAnalysis.ResolveTypeAsync(solution, document.Project, document.ClassName);
            if (facts is null) continue;

            methods.Add(new
            {
                type = facts.FullName,
                exists = facts.MemberNames.Contains(method),
                file = facts.FilePath,
                line = facts.Line,
            });
        }

        return new
        {
            action = "handler",
            method,
            referenceCount = references.Count,
            references,
            codeBehind = methods,
            note = methods.Count == 0 ? "The code-behind type could not be resolved." : null,
        };
    }
}
